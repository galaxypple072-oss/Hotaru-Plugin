#!/usr/bin/env python3
"""Build a clean, inspectable dual-character distribution without user assets."""
import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import tarfile
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]

def build(output):
    metadata = json.loads((ROOT / 'dsh-plugin/package.json').read_text())
    version = metadata['version']
    if not re.fullmatch(r'\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?', version):
        raise ValueError('invalid package version')
    output.mkdir(parents=True, exist_ok=True)
    character = metadata.get('agentsTime', {}).get('character', 'all')
    label = {'all': 'Characters', 'emilia': 'Emilia-X1', 'hotaru': 'Hotaru'}[character]
    name = f'Agents-Time-{label}-{version}'
    with tempfile.TemporaryDirectory(prefix='agents-time-release-') as temp:
        stage = Path(temp) / name
        package = stage / 'package'
        package.mkdir(parents=True)
        for entry in metadata['files'] + ['package.json']:
            if entry == 'assets/avatars':
                continue  # Source-only repositories intentionally omit images.
            src = ROOT / 'dsh-plugin' / entry
            if not src.exists() or src.is_symlink():
                raise ValueError(f'missing or symlinked package entry: {entry}')
            files = sorted(src.rglob('*')) if src.is_dir() else [src]
            for file in files:
                if file.is_symlink():
                    raise ValueError(f'symlinked file: {file}')
                if not file.is_file():
                    continue
                relative = file.relative_to(ROOT / 'dsh-plugin')
                if relative.parts[:2] == ('assets', 'avatars'):
                    continue  # Original letter avatars are generated by code.
                if file.suffix.lower() in {'.wav', '.mp3', '.moc3', '.pth', '.ckpt', '.sqlite', '.db'}:
                    raise ValueError(f'private/model asset in package allowlist: {relative}')
                target = package / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(file, target)
        readme = (ROOT / 'distribution/README.md').read_text().replace('0.1.0', version)
        (stage / 'README.md').write_text(readme)
        (package / 'README.md').write_text(readme)
        shutil.copyfile(ROOT / 'dsh-plugin/services.example.json', stage / 'services.example.json')
        installer = (ROOT / 'distribution/Install.command').read_text().replace('__VERSION__', version)
        if character != 'all':
            model = 'Emilia X1' if character == 'emilia' else 'Hotaru V0.1'
            installer = installer.replace('Emilia X1 + Hotaru V0.1', model).replace('Emilia X1 或 Hotaru V0.1', model)
        (stage / 'Install.command').write_text(installer)
        (stage / 'Install.command').chmod(0o755)
        # Check all relative JS imports are actually shipped, not just declared.
        for file in package.rglob('*.js'):
            source = file.read_text()
            if re.search(r'/Users/emilia/|/Volumes/extra/', source):
                raise ValueError(f'author-specific path: {file.name}')
            for specifier in re.findall(r"(?:from\s+|import\s*)['\"](\.[^'\"]+)['\"]", source):
                resolved = (file.parent / specifier).resolve()
                if not resolved.is_relative_to(package.resolve()) or not resolved.is_file():
                    raise ValueError(f'unshipped import: {file.name}: {specifier}')
        sums = []
        for file in sorted(stage.rglob('*')):
            if file.is_file():
                sums.append(f'{hashlib.sha256(file.read_bytes()).hexdigest()}  {file.relative_to(stage).as_posix()}\n')
        (stage / 'SHA256SUMS').write_text(''.join(sums))
        tar_path = output / f'emilia-companion-loop-{version}.tgz'
        with tar_path.open('wb') as raw, gzip.GzipFile(fileobj=raw, mode='wb', mtime=0, filename='') as compressed, tarfile.open(fileobj=compressed, mode='w') as tar:
            for file in sorted(package.rglob('*')):
                if file.is_file():
                    content = file.read_bytes()
                    info = tarfile.TarInfo('package/' + file.relative_to(package).as_posix())
                    info.size = len(content)
                    info.mode = 0o644
                    info.mtime = 0
                    tar.addfile(info, io.BytesIO(content))
        zip_path = output / f'{name}.zip'
        with zipfile.ZipFile(zip_path, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
            for file in sorted(stage.rglob('*')):
                if file.is_file():
                    info = zipfile.ZipInfo(f'{name}/{file.relative_to(stage).as_posix()}', date_time=(2026, 1, 1, 0, 0, 0))
                    info.create_system = 3
                    info.external_attr = (0o100755 if file.name == 'Install.command' else 0o100644) << 16
                    archive.writestr(info, file.read_bytes(), compress_type=zipfile.ZIP_DEFLATED)
        (output / 'SHA256SUMS').write_text(''.join(f'{hashlib.sha256(file.read_bytes()).hexdigest()}  {file.name}\n' for file in [zip_path, tar_path]))
    print(json.dumps({'version': version, 'zip': str(zip_path), 'plugin': str(tar_path), 'checksums': str(output / 'SHA256SUMS')}, ensure_ascii=False))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, default=ROOT / 'dist' / 'characters')
    build(parser.parse_args().output.resolve())
